#!/usr/bin/env python3
"""Stage only public fixture code in /var/tmp and run without production Telegram access.

Requires root on the installed Linux PSY host. Does not restart services or install anything.
The group example uses the existing Codex login. Upload uses a private network namespace,
the existing offline Whisper model and only synthetic audio generated by generate_reference.py.
"""
import argparse
import os
from pathlib import Path
import pwd
import shutil
import subprocess
import sys
import tempfile


REPOSITORY = Path(__file__).resolve().parents[2]


def clean_environment(home, temporary, *, hermes_home=None):
    environment = {'PATH': '/usr/local/bin:/usr/bin:/bin', 'HOME': str(home),
                   'TMPDIR': str(temporary), 'LANG': 'C.UTF-8', 'PYTHONDONTWRITEBYTECODE': '1'}
    if hermes_home is not None:
        environment['HERMES_HOME'] = str(hermes_home)
    return environment


def group_python(checkout, hermes_home):
    """Read the committed PM selection. Never call hermes_bootstrap or a launcher."""
    old_path = list(sys.path)
    old_home = os.environ.get('HERMES_HOME')
    old_bytecode = sys.dont_write_bytecode
    try:
        sys.dont_write_bytecode = True
        os.environ['HERMES_HOME'] = str(hermes_home)
        sys.path.insert(0, str(checkout))
        from pm.environments import committed_venv, venv_python
        environment = committed_venv(checkout)
        if environment is None:
            raise RuntimeError('No committed Hermes dependency environment')
        # Resolve the venv link to the standalone store interpreter. The test adds
        # committed site-packages itself without running .pth or updater hooks.
        interpreter = venv_python(environment).resolve(strict=True)
        if not interpreter.is_file() or not os.access(interpreter, os.X_OK):
            raise RuntimeError('The selected Hermes interpreter is unavailable')
        return interpreter
    finally:
        sys.path[:] = old_path
        sys.dont_write_bytecode = old_bytecode
        if old_home is None:
            os.environ.pop('HERMES_HOME', None)
        else:
            os.environ['HERMES_HOME'] = old_home


def stage_public_sources(destination):
    sources = [Path('tests/isolated') / name for name in
               ('group_example.py', 'upload_example.py', 'upload_ui_example.cjs')]
    sources += [path.relative_to(REPOSITORY) for path in sorted((REPOSITORY / 'media').glob('*.py'))]
    sources += [Path('media/static/app.js'), Path('common/psy_common.py')]
    for relative in sources:
        source = REPOSITORY / relative
        if source.is_symlink() or not source.is_file():
            raise RuntimeError('A fixture source must be a regular public source file')
        target = destination / relative
        target.parent.mkdir(mode=0o755, parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        target.chmod(0o644)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('example', choices=('group', 'upload'))
    parser.add_argument('--checkout', type=Path, default=Path('/home/hermes/.hermes/hermes-agent'))
    parser.add_argument('--hermes-home', type=Path, default=Path('/home/hermes/.hermes'))
    parser.add_argument('--source', type=Path, help='synthetic WAV generated in a private temp fixture directory')
    parser.add_argument('--fixture-dir', type=Path, help='the same --fixture-dir used for synthetic WAV generation')
    parser.add_argument('--upload-python', type=Path, default=Path('/opt/psy-upload-venv/bin/python'))
    parser.add_argument('--asr-python', type=Path, default=Path('/opt/psy-asr-venv/bin/python'))
    parser.add_argument('--model', type=Path, default=Path('/opt/psy-asr-model'))
    parser.add_argument('--stub-model', action='store_true', help='group wiring only. Never a real model acceptance result')
    args = parser.parse_args()
    if sys.platform != 'linux' or os.geteuid() != 0:
        parser.error('This helper requires root on the installed Linux host')
    if args.example == 'upload' and (not args.source or not args.fixture_dir or args.stub_model):
        parser.error('Upload requires --source and --fixture-dir, without --stub-model')
    user = pwd.getpwnam('hermes' if args.example == 'group' else 'psy-deliver')
    runuser = shutil.which('runuser')
    if not runuser:
        parser.error('The existing runuser binary is required')
    if args.example == 'upload':
        # Validate the existing generated source separately from generator's no-overwrite check.
        from generate_reference import validate_destination
        root = args.fixture_dir.resolve(strict=True)
        validate_destination(root, root / 'unused-destination-check.wav')
        source = args.source.resolve(strict=True)
        if (args.source.is_symlink() or source.parent != root or source.suffix.lower() != '.wav'
                or not source.is_file() or not 20 * 1024 ** 2 < source.stat().st_size < 64 * 1024 ** 2):
            parser.error('Source must be the generated synthetic WAV directly in the declared private fixture directory')
        unshare, ip = shutil.which('unshare'), shutil.which('ip')
        if not unshare or not ip:
            parser.error('Existing unshare and ip binaries are required')
    with tempfile.TemporaryDirectory(prefix='psy-isolated-run-', dir='/var/tmp') as temporary:
        root = Path(temporary)
        os.chown(root, user.pw_uid, user.pw_gid)
        code = root / 'code'
        stage_public_sources(code)
        state = root / 'state'
        state.mkdir(mode=0o700)
        os.chown(state, user.pw_uid, user.pw_gid)
        environment = clean_environment(user.pw_dir, state,
            hermes_home=args.hermes_home.resolve(strict=True) if args.example == 'group' else None)
        if args.example == 'group':
            interpreter = group_python(args.checkout.resolve(strict=True), args.hermes_home.resolve(strict=True))
            command = [str(interpreter), str(code / 'tests/isolated/group_example.py'), '--checkout', str(args.checkout.resolve())]
            if args.stub_model:
                command.append('--stub-model')
        else:
            staged_source = root / 'synthetic-reference.wav'
            shutil.copyfile(source, staged_source)
            os.chown(staged_source, user.pw_uid, user.pw_gid)
            staged_source.chmod(0o600)
            for interpreter in (args.upload_python, args.asr_python):
                if not interpreter.is_file() or not os.access(interpreter, os.X_OK):
                    parser.error('The installed upload and ASR Python environments are required')
            # Preserve each virtualenv entry point. Resolving its symlink would
            # start the base interpreter without installed aiohttp or Whisper.
            command = [str(args.upload_python.absolute()), str(code / 'tests/isolated/upload_example.py'),
                       '--source', str(staged_source), '--asr-python', str(args.asr_python.absolute()),
                       '--model', str(args.model.resolve(strict=True))]
        child = [runuser, '-u', user.pw_name, '--', *command]
        if args.example == 'upload':
            # Fixed bootstrap code, no shell interpolation or inherited credentials.
            bootstrap = ('import os,subprocess,sys\n'
                         'subprocess.run([sys.argv[1],"link","set","lo","up"],check=True)\n'
                         'os.execv(sys.argv[2],sys.argv[2:])\n')
            child = [unshare, '--net', sys.executable, '-I', '-c', bootstrap, ip, *child]
        result = subprocess.run(child, env=environment, cwd=root, check=False)
        return result.returncode


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (OSError, RuntimeError, ValueError, KeyError) as error:
        # Do not echo arbitrary runtime paths or service environment on failure.
        print('On-host fixture failed: ' + type(error).__name__, file=sys.stderr)
        raise SystemExit(1)
